// The Fanvil, Gigaset and Poly files follow the vendor provisioning guides. They were added in
// phase 3 and still need a check on real hardware, like the Grandstream memory keys.

// Fanvil builds <mac>.cfg in the Fanvil "VOIP CONFIG FILE" format (X series, firmware 2.x).
func Fanvil(in Input) string {
	var b strings.Builder
	w := func(k string, v any) { fmt.Fprintf(&b, "%-19s:%v\n", k, v) }
	b.WriteString("<<VOIP CONFIG FILE>>Version:2.0002\n\n")
	b.WriteString("<GLOBAL CONFIG MODULE>\n")
	w("Enable SNTP", 1)
	w("SNTP Server", in.Settings.NTPServer)
	w("Time Zone", 4) // index of UTC+1
	w("Time Zone Name", "UTC+1")
	w("Enable DST", 2) // automatic
	if in.Settings.Language == "nl" {
		w("Language", "nl")
	} else {
		w("Language", "en")
	}
	b.WriteString("\n<SIP CONFIG MODULE>\n")
	w("SIP  Port", in.PBX.SIPPort)
	b.WriteString("--SIP Line List--  :\n")
	if in.Ext != nil {
		transport := map[string]int{"udp": 0, "tcp": 1, "tls": 3}[in.Ext.Transport]
		w("SIP1 Phone Number", in.Ext.Number)
		w("SIP1 Display Name", clean(in.Ext.Name))
		w("SIP1 Register Addr", in.Server)
		w("SIP1 Register Port", in.port())
		w("SIP1 Register User", in.Ext.Number)
		w("SIP1 Register Pswd", clean(in.Ext.SIPSecret))
		w("SIP1 Register TTL", 300)
		w("SIP1 Enable Reg", 1)
		w("SIP1 Transport", transport)
		w("SIP1 MWI Num", "*97")
		w("SIP1 Sub MWI", 1)
		w("SIP1 RTP Encrypt", b2i(in.Ext.SRTP))
		w("SIP1 DTMF Mode", 1) // RFC 2833
		w("SIP1 Enable BLF List", 1)
	} else {
		w("SIP1 Enable Reg", 0)
	}
	// Intercom: the phone answers on the speaker when the INVITE carries Call-Info answer-after.
	ic := in.Phone.Options.Intercom
	b.WriteString("\n<PHONE FEATURE MODULE>\n")
	w("Enable Intercom", b2i(ic.Allow))
	w("Enable Intercom Mute", b2i(ic.Mute))
	w("Enable Intercom Tone", b2i(ic.Tone))
	w("Enable Intercom Barge", b2i(ic.Barge))
	b.WriteString("\n<MMI CONFIG MODULE>\n")
	b.WriteString("--MMI Account--    :\n")
	w("Account1 Name", "admin")
	w("Account1 Password", clean(in.Settings.AdminPassword))
	w("Account1 Level", 10)
	if len(in.Phone.Keys) > 0 {
		b.WriteString("\n<DSS CONFIG MODULE>\n")
		for i, k := range simpleKeys(in.Phone.Keys) {
			n := i + 1
			typ, val := 0, ""
			switch k.Type {
			case "line":
				typ, val = 2, "SIP1"
			case "blf":
				// Memory key, BLF with directed pickup.
				typ, val = 1, k.Value+"@1/ba"
			case "speed":
				typ, val = 1, k.Value+"@1/f"
			}
			w(fmt.Sprintf("Fkey%d Type", n), typ)
			w(fmt.Sprintf("Fkey%d Value", n), val)
			w(fmt.Sprintf("Fkey%d Title", n), clean(k.Label))
		}
	}
	b.WriteString("\n<<END OF FILE>>\n")
	return b.String()
}

func b2i(v bool) int {
	if v {
		return 1
	}
	return 0
}

// Gigaset builds the provisioning file of a Gigaset N670 / N870 IP PRO DECT system. Account N goes
// to handset N (the order in which handsets are registered at the base).
func Gigaset(in Input) string {
	var b strings.Builder
	p := func(name string, v any) {
		fmt.Fprintf(&b, "    <param name=\"%s\" value=\"%s\"/>\n", name, x(fmt.Sprint(v)))
	}
	product := ""
	if strings.HasPrefix(in.Phone.Model, "N870") {
		product = ` productID="e2"`
	}
	fmt.Fprintf(&b, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by Kiestoon -->\n<provisioning version=\"1.1\"%s>\n  <nvm>\n", product)
	p("Ntp.0.Server", in.Settings.NTPServer)
	p("Ntp.0.TimeZone", "Europe/Amsterdam")
	p("WebUI.0.AdminPassword", in.Settings.AdminPassword)
	if in.Settings.Language == "nl" {
		p("System.0.Language", "nl")
	} else {
		p("System.0.Language", "en")
	}
	transport := 1 // UDP
	if in.Ext != nil {
		switch in.Ext.Transport {
		case "tcp":
			transport = 2
		case "tls":
			transport = 3
		}
	}
	p("SipProvider.0.Name", in.Org)
	p("SipProvider.0.Domain", in.Server)
	p("SipProvider.0.ProxyServerAddress", in.Server)
	p("SipProvider.0.ProxyServerPort", in.port())
	p("SipProvider.0.RegServerAddress", in.Server)
	p("SipProvider.0.RegServerPort", in.port())
	p("SipProvider.0.RegServerRefreshTimer", 300)
	p("SipProvider.0.TransportProtocol", transport)
	p("SipProvider.0.DtmfTransmission", 2) // RFC 2833
	exts := []*pbx.Extension{}
	if in.Ext != nil {
		exts = append(exts, in.Ext)
	}
	exts = append(exts, in.Lines...)
	for i, e := range exts {
		pre := fmt.Sprintf("SipAccount.%d.", i)
		p(pre+"Active", 1)
		p(pre+"ProviderId", 0)
		p(pre+"AuthName", e.Number)
		p(pre+"AuthPassword", clean(e.SIPSecret))
		p(pre+"UserName", e.Number)
		p(pre+"DisplayName", clean(e.Name))
		p(pre+"VoiceMailboxNumber", "*97")
		p(pre+"VoiceMailboxActive", 1)
		p(fmt.Sprintf("hS.%d.SipAccountId", i), i)
	}
	b.WriteString("  </nvm>\n</provisioning>\n")
	return b.String()
}

// PolyMaster is the master configuration file (000000000000.cfg and <mac>.cfg) of a Poly phone: it
// points to kiestoon-<mac>.cfg, which holds the settings, and to the firmware (sip.ld) when one is set.
func PolyMaster(firmware string) string {
	return "<?xml version=\"1.0\" standalone=\"yes\"?>\n<!-- Generated by Kiestoon -->\n" +
		"<APPLICATION APP_FILE_PATH=\"" + x(firmware) + "\" CONFIG_FILES=\"kiestoon-[PHONE_MAC_ADDRESS].cfg\" MISC_FILES=\"\" LOG_FILE_DIRECTORY=\"\" " +
		"OVERRIDES_DIRECTORY=\"\" CONTACTS_DIRECTORY=\"\" LICENSE_DIRECTORY=\"\" USER_PROFILES_DIRECTORY=\"\" CALL_LISTS_DIRECTORY=\"\" COREFILE_DIRECTORY=\"\"/>\n"
}

// Poly builds kiestoon-<mac>.cfg for Poly VVX and Edge E phones (UC Software / PVOS).
func Poly(in Input) string {
	var b strings.Builder
	attrs := func(tag string, kv [][2]string) {
		fmt.Fprintf(&b, "  <%s", tag)
		for _, a := range kv {
			fmt.Fprintf(&b, "\n    %s=\"%s\"", a[0], x(a[1]))
		}
		b.WriteString("/>\n")
	}
	b.WriteString("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<!-- Generated by Kiestoon -->\n<polycomConfig>\n")
	lang := "English_United_Kingdom"
	if in.Settings.Language == "nl" {
		lang = "Nederlands_Nederland"
	}
	attrs("device", [][2]string{
		{"device.set", "1"},
		{"device.auth.localAdminPassword.set", "1"}, {"device.auth.localAdminPassword", in.Settings.AdminPassword},
		{"device.sntp.serverName.set", "1"}, {"device.sntp.serverName", in.Settings.NTPServer},
		{"device.sntp.gmtOffset.set", "1"}, {"device.sntp.gmtOffset", "3600"},
	})
	attrs("tcpIpApp", [][2]string{
		{"tcpIpApp.sntp.address", in.Settings.NTPServer}, {"tcpIpApp.sntp.gmtOffset", "3600"},
		{"tcpIpApp.sntp.daylightSavings.enable", "1"},
	})
	attrs("lcl", [][2]string{{"lcl.ml.lang", lang}, {"lcl.datetime.date.format", "D,dM"}, {"lcl.datetime.time.24HourClock", "1"}})
	if in.Ext != nil {
		transport := map[string]string{"udp": "UDPOnly", "tcp": "TCPOnly", "tls": "TLS"}[in.Ext.Transport]
		srtp := fmt.Sprint(b2i(in.Ext.SRTP))
		attrs("reg", [][2]string{
			{"reg.1.displayName", clean(in.Ext.Name)}, {"reg.1.label", clean(in.Ext.Number)}, {"reg.1.address", in.Ext.Number},
			{"reg.1.auth.userId", in.Ext.Number}, {"reg.1.auth.password", clean(in.Ext.SIPSecret)},
			{"reg.1.server.1.address", in.Server}, {"reg.1.server.1.port", fmt.Sprint(in.port())},
			{"reg.1.server.1.transport", transport}, {"reg.1.server.1.expires", "300"}, {"reg.1.lineKeys", "1"},
			{"reg.1.srtp.enable", srtp}, {"reg.1.srtp.offer", srtp}, {"reg.1.srtp.require", srtp},
		})
		attrs("msg", [][2]string{{"msg.mwi.1.subscribe", in.Ext.Number}, {"msg.mwi.1.callBackMode", "contact"}, {"msg.mwi.1.callBack", "*97"}})
	}
	// Intercom: Poly does not read Call-Info, it matches the Alert-Info header that Kiestoon sends
	// (info=alert-autoanswer) to the autoAnswer ring class. Without intercom the rules fall back to
	// the normal ring.
	class := "default"
	if in.Phone.Options.Intercom.Allow {
		class = "autoAnswer"
	}
	attrs("voIpProt", [][2]string{
		{"voIpProt.SIP.alertInfo.1.value", "info=alert-autoanswer"}, {"voIpProt.SIP.alertInfo.1.class", class},
		{"voIpProt.SIP.alertInfo.2.value", "alert-autoanswer"}, {"voIpProt.SIP.alertInfo.2.class", class},
	})
	attrs("se", [][2]string{{"se.rt.autoAnswer.timeout", "0"}})
	attrs("call", [][2]string{{"call.autoAnswer.micMute", fmt.Sprint(b2i(in.Phone.Options.Intercom.Mute))}})
	kv := [][2]string{}
	n := 0
	for _, k := range simpleKeys(in.Phone.Keys) {
		typ := ""
		switch k.Type {
		case "blf":
			typ = "normal"
		case "speed":
			typ = "automata"
		default:
			continue
		}
		n++
		pre := fmt.Sprintf("attendant.resourceList.%d.", n)
		kv = append(kv, [2]string{pre + "address", k.Value}, [2]string{pre + "label", clean(k.Label)}, [2]string{pre + "type", typ})
	}
	if len(kv) > 0 {
		attrs("attendant", append([][2]string{{"attendant.reg", "1"}}, kv...))
	}
	b.WriteString("</polycomConfig>\n")
	return b.String()
}
