// Package wg builds WireGuard configuration for the tunnels between Kiestoon systems: the hub of a
// central Kiestoon (edges and federated sites connect to it), the links to other hubs, and the link
// between the two nodes of a high-availability pair.
//
// Every tunnel is a wg-quick interface whose name starts with "kt". The portal decides what the
// interfaces look like; the root helper writes /etc/wireguard/<name>.conf and brings them up.
package wg

import (
	"bufio"
	"crypto/ecdh"
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"net"
	"net/netip"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

// Marker is the first line of every configuration file Kiestoon writes.
const Marker = "# Generated by Kiestoon. Changes are overwritten."

// Peer is the other side of a tunnel.
type Peer struct {
	PublicKey string `json:"publicKey"`
	// AllowedIPs are the tunnel addresses of the peer (normally one /32).
	AllowedIPs []string `json:"allowedIps"`
	// Endpoint is host:port of the peer. Empty for peers that connect to us.
	Endpoint string `json:"endpoint,omitempty"`
	// Keepalive in seconds keeps NAT mappings open (25 for the side behind NAT).
	Keepalive int `json:"keepalive,omitempty"`
}

// Interface is one wg-quick interface.
type Interface struct {
	Name       string `json:"name"`
	PrivateKey string `json:"privateKey"`
	// Address is the own tunnel address with prefix, for example 10.77.12.1/24.
	Address    string `json:"address"`
	ListenPort int    `json:"listenPort,omitempty"`
	Peers      []Peer `json:"peers"`
}

var (
	reName     = regexp.MustCompile(`^kt[a-z0-9-]{0,13}$`)
	reEndpoint = regexp.MustCompile(`^(\[[0-9a-fA-F:.]+\]|[a-zA-Z0-9.-]{1,253}):[0-9]{1,5}$`)
)

// ValidKey reports whether k is a base64 WireGuard key (32 bytes).
func ValidKey(k string) bool {
	b, err := base64.StdEncoding.DecodeString(k)
	return err == nil && len(b) == 32
}

// ValidEndpoint reports whether e is host:port.
func ValidEndpoint(e string) bool {
	if !reEndpoint.MatchString(e) {
		return false
	}
	_, p, _ := net.SplitHostPort(e)
	n, err := strconv.Atoi(p)
	return err == nil && n > 0 && n < 65536
}

// Validate checks everything that ends up in the configuration file.
func (i *Interface) Validate() error {
	if !reName.MatchString(i.Name) {
		return errors.New("invalid interface name")
	}
	if !ValidKey(i.PrivateKey) {
		return errors.New("invalid private key")
	}
	if _, err := netip.ParsePrefix(i.Address); err != nil {
		return errors.New("invalid address")
	}
	if i.ListenPort < 0 || i.ListenPort > 65535 {
		return errors.New("invalid listen port")
	}
	seen := map[string]bool{}
	for _, p := range i.Peers {
		if !ValidKey(p.PublicKey) || seen[p.PublicKey] {
			return errors.New("invalid peer key")
		}
		seen[p.PublicKey] = true
		if len(p.AllowedIPs) == 0 {
			return errors.New("peer without allowed ips")
		}
		for _, a := range p.AllowedIPs {
			if _, err := netip.ParsePrefix(a); err != nil {
				return errors.New("invalid allowed ip")
			}
		}
		if p.Endpoint != "" && !ValidEndpoint(p.Endpoint) {
			return errors.New("invalid endpoint")
		}
		if p.Keepalive < 0 || p.Keepalive > 3600 {
			return errors.New("invalid keepalive")
		}
	}
	return nil
}

// Render builds the wg-quick configuration file. withAddress=false leaves out the wg-quick only
// lines (Address), which is the format `wg syncconf` takes.
func (i *Interface) Render(withAddress bool) string {
	var b strings.Builder
	b.WriteString(Marker + "\n[Interface]\n")
	fmt.Fprintf(&b, "PrivateKey = %s\n", i.PrivateKey)
	if withAddress {
		fmt.Fprintf(&b, "Address = %s\n", i.Address)
	}
	if i.ListenPort > 0 {
		fmt.Fprintf(&b, "ListenPort = %d\n", i.ListenPort)
	}
	peers := append([]Peer{}, i.Peers...)
	sort.Slice(peers, func(a, c int) bool { return peers[a].PublicKey < peers[c].PublicKey })
	for _, p := range peers {
		b.WriteString("\n[Peer]\n")
		fmt.Fprintf(&b, "PublicKey = %s\n", p.PublicKey)
		fmt.Fprintf(&b, "AllowedIPs = %s\n", strings.Join(p.AllowedIPs, ", "))
		if p.Endpoint != "" {
			fmt.Fprintf(&b, "Endpoint = %s\n", p.Endpoint)
		}
		if p.Keepalive > 0 {
			fmt.Fprintf(&b, "PersistentKeepalive = %d\n", p.Keepalive)
		}
	}
	return b.String()
}

// NewKey returns a new private key and its public key, base64 encoded.
func NewKey() (private, public string, err error) {
	k, err := ecdh.X25519().GenerateKey(rand.Reader)
	if err != nil {
		return "", "", err
	}
	return base64.StdEncoding.EncodeToString(k.Bytes()), base64.StdEncoding.EncodeToString(k.PublicKey().Bytes()), nil
}

// PublicKey derives the public key of a base64 private key.
func PublicKey(private string) (string, error) {
	b, err := base64.StdEncoding.DecodeString(private)
	if err != nil || len(b) != 32 {
		return "", errors.New("invalid private key")
	}
	k, err := ecdh.X25519().NewPrivateKey(b)
	if err != nil {
		return "", err
	}
	return base64.StdEncoding.EncodeToString(k.PublicKey().Bytes()), nil
}

// RandomSubnet picks a /24 in 10.64.0.0/10 for a hub. Random, so two Kiestoon systems that are
// linked later are unlikely to use the same range.
func RandomSubnet() netip.Prefix {
	var b [2]byte
	_, _ = rand.Read(b[:])
	return netip.PrefixFrom(netip.AddrFrom4([4]byte{10, 64 + b[0]%64, b[1], 0}), 24)
}

// HostAddr returns the n-th address of a subnet (1 is the hub).
func HostAddr(subnet netip.Prefix, n int) (netip.Addr, error) {
	if !subnet.Addr().Is4() || n < 1 {
		return netip.Addr{}, errors.New("invalid subnet")
	}
	size := 1 << (32 - subnet.Bits())
	if n >= size-1 {
		return netip.Addr{}, errors.New("subnet full")
	}
	a := subnet.Masked().Addr().As4()
	v := uint32(a[0])<<24 | uint32(a[1])<<16 | uint32(a[2])<<8 | uint32(a[3])
	v += uint32(n)
	return netip.AddrFrom4([4]byte{byte(v >> 24), byte(v >> 16), byte(v >> 8), byte(v)}), nil
}

// NextFree returns the lowest address from .2 on that is not in used.
func NextFree(subnet netip.Prefix, used []string) (netip.Addr, error) {
	taken := map[netip.Addr]bool{}
	for _, u := range used {
		if a, err := netip.ParseAddr(strings.Split(u, "/")[0]); err == nil {
			taken[a] = true
		}
	}
	for n := 2; ; n++ {
		a, err := HostAddr(subnet, n)
		if err != nil {
			return netip.Addr{}, err
		}
		if !taken[a] {
			return a, nil
		}
	}
}

// PeerStatus is the live state of one peer from `wg show all dump`.
type PeerStatus struct {
	Interface     string    `json:"interface"`
	PublicKey     string    `json:"publicKey"`
	Endpoint      string    `json:"endpoint"`
	LastHandshake time.Time `json:"lastHandshake"`
	RxBytes       int64     `json:"rxBytes"`
	TxBytes       int64     `json:"txBytes"`
}

// Connected reports whether the peer did a handshake in the last three minutes (WireGuard renews
// the session every two minutes while traffic flows; keepalives keep it going).
func (p PeerStatus) Connected(now time.Time) bool {
	return !p.LastHandshake.IsZero() && now.Sub(p.LastHandshake) < 3*time.Minute
}

// ParseDump reads the output of `wg show all dump`. Interface lines have 5 fields, peer lines 9.
func ParseDump(out string) []PeerStatus {
	res := []PeerStatus{}
	sc := bufio.NewScanner(strings.NewReader(out))
	for sc.Scan() {
		f := strings.Split(sc.Text(), "\t")
		if len(f) != 9 {
			continue
		}
		p := PeerStatus{Interface: f[0], PublicKey: f[1]}
		if f[3] != "(none)" {
			p.Endpoint = f[3]
		}
		if ts, err := strconv.ParseInt(f[5], 10, 64); err == nil && ts > 0 {
			p.LastHandshake = time.Unix(ts, 0).UTC()
		}
		p.RxBytes, _ = strconv.ParseInt(f[6], 10, 64)
		p.TxBytes, _ = strconv.ParseInt(f[7], 10, 64)
		res = append(res, p)
	}
	return res
}
