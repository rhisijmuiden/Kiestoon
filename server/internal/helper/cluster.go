// ClusterStatus is the live state of high availability on this node.
type ClusterStatus struct {
	KeepalivedInstalled bool   `json:"keepalivedInstalled"`
	KeepalivedActive    bool   `json:"keepalivedActive"`
	VRRPState           string `json:"vrrpState"`
	VIPHere             bool   `json:"vipHere"`
	Interface           string `json:"interface"`
	AsteriskActive      bool   `json:"asteriskActive"`
}

const keepalivedConf = "/etc/keepalived/keepalived.conf"

func (s *Server) vrrpStatePath() string { return filepath.Join(s.StateDir, "vrrp-state") }

var reDefaultDev = regexp.MustCompile(`\bdev\s+(\S+)`)

// defaultInterface is the network interface of the default route.
func defaultInterface(ctx context.Context) string {
	out, err := runCmd(ctx, "ip", "-4", "route", "show", "default")
	if err != nil {
		return ""
	}
	if m := reDefaultDev.FindStringSubmatch(out); m != nil {
		return m[1]
	}
	return ""
}

func active(ctx context.Context, unit string) bool {
	_, err := runCmd(ctx, "systemctl", "is-active", "--quiet", unit)
	return err == nil
}

// clusterApply writes the keepalived configuration from node.json (or removes it).
func (s *Server) clusterApply(ctx context.Context) (any, error) {
	n := cluster.LoadNode(s.DataDir)
	_, kaErr := exec.LookPath("keepalived")
	if !n.Enabled || n.Mode != cluster.ModeVIP || n.Peer == nil {
		if b, err := os.ReadFile(keepalivedConf); err == nil && strings.HasPrefix(string(b), "# Generated by Kiestoon") {
			_, _ = runCmd(ctx, "systemctl", "disable", "--now", "keepalived.service")
			_ = os.Remove(keepalivedConf)
		}
		if !n.Enabled {
			_ = os.Remove(s.vrrpStatePath())
			// A node without high availability runs Asterisk as usual.
			_, _ = runCmd(ctx, "systemctl", "enable", "asterisk.service")
		}
		return s.clusterStatus(ctx), nil
	}
	if kaErr != nil {
		return nil, errors.New("keepalived_missing")
	}
	iface := n.Interface
	if iface == "" {
		iface = defaultInterface(ctx)
	}
	text, err := cluster.Keepalived(n, iface)
	if err != nil {
		return nil, err
	}
	old, _ := os.ReadFile(keepalivedConf)
	if string(old) != text {
		if err := os.MkdirAll(filepath.Dir(keepalivedConf), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(keepalivedConf+".tmp", []byte(text), 0o600); err != nil {
			return nil, err
		}
		if err := os.Rename(keepalivedConf+".tmp", keepalivedConf); err != nil {
			return nil, err
		}
		_, _ = runCmd(ctx, "systemctl", "enable", "keepalived.service")
		if active(ctx, "keepalived.service") {
			_, err = runCmd(ctx, "systemctl", "reload", "keepalived.service")
		} else {
			_, err = runCmd(ctx, "systemctl", "start", "keepalived.service")
		}
		if err != nil {
			return nil, err
		}
	} else if !active(ctx, "keepalived.service") {
		_, _ = runCmd(ctx, "systemctl", "enable", "--now", "keepalived.service")
	}
	return s.clusterStatus(ctx), nil
}

func (s *Server) clusterStatus(ctx context.Context) ClusterStatus {
	n := cluster.LoadNode(s.DataDir)
	st := ClusterStatus{AsteriskActive: active(ctx, "asterisk.service")}
	if _, err := exec.LookPath("keepalived"); err == nil {
		st.KeepalivedInstalled = true
		st.KeepalivedActive = active(ctx, "keepalived.service")
	}
	if b, err := os.ReadFile(s.vrrpStatePath()); err == nil {
		st.VRRPState = strings.TrimSpace(string(b))
	}
	st.Interface = n.Interface
	if st.Interface == "" {
		st.Interface = defaultInterface(ctx)
	}
	if n.VIP != "" {
		if out, err := runCmd(ctx, "ip", "-4", "-o", "addr", "show"); err == nil {
			st.VIPHere = strings.Contains(out, " "+n.VIP+" ")
		}
	}
	return st
}

// clusterNotify is called by keepalived (through `kiestoon cluster-notify`) on every state change.
func (s *Server) clusterNotify(ctx context.Context, state string) error {
	switch state {
	case "master", "backup", "fault":
	default:
		return errors.New("invalid state")
	}
	_ = os.WriteFile(s.vrrpStatePath(), []byte(state+"\n"), 0o644)
	n := cluster.LoadNode(s.DataDir)
	if !n.Enabled {
		return nil
	}
	s.Log.Info("cluster state change", "vrrp", state)
	if state == "master" {
		return s.promote(ctx, "vrrp master")
	}
	return s.demote(ctx, "vrrp "+state, false)
}

func (s *Server) chownKiestoon(paths ...string) {
	u, err := user.Lookup("kiestoon")
	if err != nil {
		return
	}
	uid, _ := strconv.Atoi(u.Uid)
	gid, _ := strconv.Atoi(u.Gid)
	for _, p := range paths {
		_ = os.Chown(p, uid, gid)
	}
}

func copyFile(src, dst string, mode os.FileMode) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	tmp := dst + ".tmp"
	out, err := os.OpenFile(tmp, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, mode)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		os.Remove(tmp)
		return err
	}
	if err := out.Close(); err != nil {
		os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, dst)
}

// promote makes this node the primary. It uses the newest database: the replica from the other
// node, or the own database when this node was the last primary.
func (s *Server) promote(ctx context.Context, reason string) error {
	s.clusterMu.Lock()
	defer s.clusterMu.Unlock()
	role := cluster.LoadRole(s.DataDir)
	if role.Role == cluster.RolePrimary {
		_, _ = runCmd(ctx, "systemctl", "enable", "asterisk.service")
		if !active(ctx, "asterisk.service") {
			_, _ = runCmd(ctx, "systemctl", "start", "asterisk.service")
		}
		return nil
	}
	own := cluster.Meta{Epoch: role.Epoch, Seq: role.LastSeq}
	rep, ok := cluster.LoadMeta(cluster.ReplicaPath(s.DataDir))
	useReplica := ok && rep.Newer(own)
	_, _ = runCmd(ctx, "systemctl", "stop", "kiestoon.service")
	db := filepath.Join(s.DataDir, "kiestoon.db")
	if useReplica {
		stamp := time.Now().UTC().Format("20060102T150405Z")
		keep := filepath.Join(cluster.Dir(s.DataDir), "previous")
		_ = os.RemoveAll(keep)
		_ = os.MkdirAll(keep, 0o700)
		for _, suffix := range []string{"", "-wal", "-shm"} {
			_ = os.Rename(db+suffix, filepath.Join(keep, "kiestoon.db"+suffix))
		}
		_ = os.WriteFile(filepath.Join(keep, "README"), []byte("Database of this node before it was promoted at "+stamp+".\n"), 0o600)
		if err := copyFile(cluster.ReplicaPath(s.DataDir), db, 0o640); err != nil {
			// Put the own database back and stay standby.
			for _, suffix := range []string{"", "-wal", "-shm"} {
				_ = os.Rename(filepath.Join(keep, "kiestoon.db"+suffix), db+suffix)
			}
			_, _ = runCmd(ctx, "systemctl", "start", "kiestoon.service")
			return err
		}
		s.chownKiestoon(db, keep)
	}
	epoch := role.Epoch
	if ok && rep.Epoch > epoch {
		epoch = rep.Epoch
	}
	role = cluster.Role{Role: cluster.RolePrimary, Epoch: epoch + 1, Reason: reason}
	if err := cluster.SaveRole(s.DataDir, role); err != nil {
		return err
	}
	s.chownKiestoon(filepath.Join(cluster.Dir(s.DataDir), "role.json"))
	s.Log.Info("promoted to primary", "reason", reason, "replica", useReplica, "epoch", role.Epoch)
	_, _ = runCmd(ctx, "systemctl", "start", "kiestoon.service")
	_, _ = runCmd(ctx, "systemctl", "enable", "asterisk.service")
	_, err := runCmd(ctx, "systemctl", "start", "asterisk.service")
	return err
}

// demote makes this node the standby: Asterisk stops and the portal restarts as status portal.
// release also restarts keepalived, so the other node takes the virtual IP (planned switch-over).
func (s *Server) demote(ctx context.Context, reason string, release bool) error {
	s.clusterMu.Lock()
	defer s.clusterMu.Unlock()
	role := cluster.LoadRole(s.DataDir)
	_, _ = runCmd(ctx, "systemctl", "disable", "--now", "asterisk.service")
	if role.Role == cluster.RoleStandby {
		return nil
	}
	if m, ok := cluster.LoadMeta(cluster.SnapshotPath(s.DataDir)); ok && m.Epoch == role.Epoch {
		role.LastSeq = m.Seq
	}
	role.Role = cluster.RoleStandby
	role.Reason = reason
	if err := cluster.SaveRole(s.DataDir, role); err != nil {
		return err
	}
	s.chownKiestoon(filepath.Join(cluster.Dir(s.DataDir), "role.json"))
	s.Log.Info("demoted to standby", "reason", reason)
	if release && active(ctx, "keepalived.service") {
		_, _ = runCmd(ctx, "systemctl", "restart", "keepalived.service")
	}
	_, err := runCmd(ctx, "systemctl", "restart", "kiestoon.service")
	return err
}

// clusterBoot makes sure a standby never runs Asterisk after a reboot.
func (s *Server) clusterBoot(ctx context.Context) {
	if cluster.IsStandby(s.DataDir) {
		_, _ = runCmd(ctx, "systemctl", "disable", "--now", "asterisk.service")
	}
}
