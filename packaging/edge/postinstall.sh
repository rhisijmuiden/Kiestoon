#!/bin/sh
set -e
install -d -m 0700 /var/lib/kiestoon-edge
install -d -m 0700 /etc/wireguard
# Without a running systemd (image build in a chroot) systemctl ignores requests; --root works offline.
SYSTEMCTL="systemctl"
[ -d /run/systemd/system ] || SYSTEMCTL="systemctl --root=/"
# Kamailio and rtpengine run with the configuration Kiestoon Edge writes after pairing.
if ! grep -qs 'Generated by Kiestoon Edge' /etc/kamailio/kamailio.cfg; then
  $SYSTEMCTL disable kamailio.service rtpengine-daemon.service >/dev/null 2>&1 || true
  [ -d /run/systemd/system ] && systemctl stop kamailio.service rtpengine-daemon.service >/dev/null 2>&1 || true
fi
$SYSTEMCTL enable kiestoon-edge.service >/dev/null 2>&1 || true
if [ -d /run/systemd/system ]; then
  sysctl -q -p /usr/lib/sysctl.d/60-kiestoon-edge.conf >/dev/null 2>&1 || true
  systemctl daemon-reload
  systemctl restart kiestoon-edge.service
fi
exit 0
