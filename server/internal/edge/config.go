// Package edge is Kiestoon Edge: a small satellite for a branch office (a Raspberry Pi, an LXC
// container or any Debian 13 machine). It builds a WireGuard tunnel to the central Kiestoon,
// so the office needs no port forwarding, and runs a local SIP proxy (Kamailio) and media relay
// (rtpengine) for the phones in the office. Phones talk to the edge on the LAN; the edge talks to
// the central Kiestoon through the tunnel. NAT problems between the office and the data centre are
// gone because only the tunnel crosses the NAT.
package edge

import (
	"fmt"
	"net/netip"
	"strings"
)

// Ports of the edge relay.
const (
	SIPPort  = 5060
	RTPStart = 30000
	RTPEnd   = 39999
	// Interface is the WireGuard interface of the edge.
	Interface = "kt-edge"
)

// ProxyConfig is everything the Kamailio and rtpengine configuration depends on.
type ProxyConfig struct {
	LANAddress string // the edge in the office network
	TunnelIP   string // the edge in the tunnel
	HubIP      string // the central Kiestoon in the tunnel
	HubSIPPort int
	RTPStart   int
	RTPEnd     int
}

// Validate rejects anything that is not a plain address, so nothing else can end up in the files.
func (c ProxyConfig) Validate() error {
	for _, a := range []string{c.LANAddress, c.TunnelIP, c.HubIP} {
		if ip, err := netip.ParseAddr(a); err != nil || !ip.Is4() {
			return fmt.Errorf("invalid address %q", a)
		}
	}
	if c.HubSIPPort < 1 || c.HubSIPPort > 65535 || c.RTPStart < 1024 || c.RTPEnd <= c.RTPStart || c.RTPEnd > 65535 {
		return fmt.Errorf("invalid ports")
	}
	return nil
}

// Kamailio builds /etc/kamailio/kamailio.cfg.
//
// Requests from phones go to the central Kiestoon; REGISTER gets a Path header, so the central
// Asterisk sends calls for the phone back through this proxy. Requests from the central Kiestoon go
// to the phone (the ;alias parameter on the contact holds the phone's real address). rtpengine
// anchors the media between the office network and the tunnel.
func Kamailio(c ProxyConfig) string {
	r := strings.NewReplacer("@LAN@", c.LANAddress, "@WG@", c.TunnelIP, "@HUB@", c.HubIP, "@HUBPORT@", fmt.Sprint(c.HubSIPPort))
	return r.Replace(kamailioTemplate)
}

const kamailioTemplate = `#!KAMAILIO
# Generated by Kiestoon Edge. Changes are overwritten.
#
# Office phones  <-- @LAN@:5060 -->  Kiestoon Edge  <-- @WG@ (WireGuard) -->  Kiestoon @HUB@:@HUBPORT@

debug=2
log_stderror=no
log_facility=LOG_LOCAL0
log_prefix="{$mt $hdr(CSeq) $ci} "
children=4
tcp_children=4
auto_aliases=no
ip_free_bind=1
# The tunnel only carries packets from the tunnel address: pick the source by the routing table.
mhomed=1
listen=udp:@LAN@:5060
listen=tcp:@LAN@:5060
listen=udp:@WG@:5060
listen=tcp:@WG@:5060
tcp_connection_lifetime=3605
tcp_keepalive=yes
server_header="Server: Kiestoon Edge"
user_agent_header="User-Agent: Kiestoon Edge"

loadmodule "jsonrpcs.so"
loadmodule "kex.so"
loadmodule "corex.so"
loadmodule "tm.so"
loadmodule "tmx.so"
loadmodule "sl.so"
loadmodule "rr.so"
loadmodule "pv.so"
loadmodule "maxfwd.so"
loadmodule "textops.so"
loadmodule "siputils.so"
loadmodule "xlog.so"
loadmodule "sanity.so"
loadmodule "ctl.so"
loadmodule "path.so"
loadmodule "nathelper.so"
loadmodule "rtpengine.so"
loadmodule "pike.so"

modparam("jsonrpcs", "transport", 2)
modparam("rr", "enable_double_rr", 1)
modparam("rr", "append_fromtag", 1)
modparam("path", "use_received", 0)
modparam("nathelper", "natping_interval", 0)
modparam("rtpengine", "rtpengine_sock", "udp:127.0.0.1:2223")
modparam("tm", "fr_timer", 5000)
modparam("tm", "fr_inv_timer", 120000)
# Flood protection for the office side (the central Kiestoon is never limited).
modparam("pike", "sampling_time_unit", 2)
modparam("pike", "reqs_density_per_unit", 40)
modparam("pike", "remove_latency", 4)

request_route {
	if (!mf_process_maxfwd_header("10")) {
		sl_send_reply("483", "Too Many Hops");
		exit;
	}
	if (!sanity_check()) {
		exit;
	}
	$var(central) = 0;
	if ($si == "@HUB@") {
		$var(central) = 1;
	} else if (!pike_check_req()) {
		xlog("L_ALERT", "kiestoon-edge: flood from $si\n");
		exit;
	}

	if (is_method("CANCEL")) {
		if (t_check_trans()) {
			route(MEDIA);
			route(RELAY);
		}
		exit;
	}
	if (!is_method("ACK")) {
		if (t_precheck_trans()) {
			t_check_trans();
			exit;
		}
		t_check_trans();
	}

	# Requests inside a call.
	if (has_totag()) {
		if (loose_route()) {
			if ($var(central) == 1) {
				handle_ruri_alias();
			} else {
				add_contact_alias();
			}
			route(MEDIA);
			route(RELAY);
		}
		if (is_method("ACK")) {
			if (t_check_trans()) {
				route(RELAY);
			}
			exit;
		}
		sl_send_reply("404", "Not here");
		exit;
	}

	if ($var(central) == 1) {
		# To a phone in the office: the Route from the Path header points at us.
		loose_route();
		handle_ruri_alias();
		if (is_method("INVITE|SUBSCRIBE|REFER")) {
			record_route();
		}
		route(MEDIA);
		route(RELAY);
	}

	# From a phone in the office: everything goes to the central Kiestoon.
	remove_hf("Route");
	add_contact_alias();
	if (is_method("REGISTER")) {
		add_path();
		# Asterisk only accepts the Path header when the registration says it supports it.
		append_hf("Supported: path\r\n");
	} else if (is_method("INVITE|SUBSCRIBE|REFER")) {
		record_route();
	}
	$du = "sip:@HUB@:@HUBPORT@";
	route(MEDIA);
	route(RELAY);
}

route[MEDIA] {
	if ($var(central) == 1) {
		$avp(rtpflags) = "direction=wg direction=lan replace-origin replace-session-connection ICE=remove";
	} else {
		$avp(rtpflags) = "direction=lan direction=wg replace-origin replace-session-connection ICE=remove";
	}
	if (has_body("application/sdp") || is_method("BYE|CANCEL")) {
		rtpengine_manage("$avp(rtpflags)");
	}
}

route[RELAY] {
	if (is_method("INVITE|UPDATE")) {
		t_on_reply("REPLY");
	}
	if (!t_relay()) {
		sl_reply_error();
	}
	exit;
}

onreply_route[REPLY] {
	if ($si != "@HUB@") {
		add_contact_alias();
	}
	if (has_body("application/sdp")) {
		rtpengine_manage("$avp(rtpflags)");
	}
}
`

// RTPEngine builds /etc/rtpengine/rtpengine.conf: one interface in the office, one in the tunnel.
func RTPEngine(c ProxyConfig) string {
	return fmt.Sprintf(`# Generated by Kiestoon Edge. Changes are overwritten.
[rtpengine]
table = -1
interface = lan/%s;wg/%s
listen-ng = 127.0.0.1:2223
port-min = %d
port-max = %d
tos = 184
timeout = 60
silent-timeout = 3600
log-level = 5
log-facility = local1
`, c.LANAddress, c.TunnelIP, c.RTPStart, c.RTPEnd)
}
