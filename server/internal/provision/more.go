// Htek, Akuvox and Cisco MPP were added in phase 4 after the vendor provisioning guides; like the
// Fanvil, Gigaset and Poly files they still need a check on real hardware.

// Htek builds cfg<mac>.xml for Htek UC9xx phones. Htek uses the same P-value numbers as the classic
// Grandstream format for the first account.
func Htek(in Input) string {
	var b strings.Builder
	p := func(n int, v any) { fmt.Fprintf(&b, "    <P%d>%s</P%d>\n", n, x(fmt.Sprint(v)), n) }
	fmt.Fprintf(&b, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by Kiestoon -->\n<hl_provision version=\"1\">\n  <config version=\"1\">\n")
	p(2, in.Settings.AdminPassword)
	p(30, in.Settings.NTPServer)
	p(64, "CET-1CEST-2,M3.5.0/02:00:00,M10.5.0/03:00:00")
	if in.Settings.Lang() == "nl" {
		p(1362, "nl")
	} else {
		p(1362, "en")
	}
	if in.Ext != nil {
		_, gt, _ := transportCode(in.Ext.Transport)
		p(271, 1)
		p(270, in.Ext.Number+" "+in.Ext.Name)
		p(47, fmt.Sprintf("%s:%d", in.Server, in.port()))
		p(35, in.Ext.Number)
		p(36, in.Ext.Number)
		p(34, in.Ext.SIPSecret)
		p(3, in.Ext.Name)
		p(33, "*97")
		p(130, gt)
		p(298, b2i(in.Phone.Options.Intercom.Allow)) // intercom: auto-answer on Call-Info
		if in.Ext.SRTP {
			p(183, 2)
		} else {
			p(183, 0)
		}
	} else {
		p(271, 0)
	}
	firmwareP(&b, p, in)
	b.WriteString("  </config>\n</hl_provision>\n")
	return b.String()
}

// firmwareP writes the firmware upgrade P-values of Grandstream and Htek: P212 the protocol
// (1 HTTP, 2 HTTPS), P192 the directory (without scheme), P238 check at every provisioning run.
func firmwareP(_ *strings.Builder, p func(int, any), in Input) {
	if in.FirmwareDir == "" {
		return
	}
	proto, path := 1, strings.TrimPrefix(in.FirmwareDir, "http://")
	if strings.HasPrefix(in.FirmwareDir, "https://") {
		proto, path = 2, strings.TrimPrefix(in.FirmwareDir, "https://")
	}
	p(212, proto)
	p(192, strings.TrimSuffix(path, "/"))
	p(238, 0)
}

// Akuvox builds <mac>.cfg for Akuvox door phones and intercoms (autop format).
func Akuvox(in Input) string {
	var b strings.Builder
	w := func(k string, v any) { fmt.Fprintf(&b, "%s = %v\n", k, v) }
	b.WriteString("## Generated by Kiestoon\n")
	w("Config.Settings.SNTP.Enable", 1)
	w("Config.Settings.SNTP.NTP1", in.Settings.NTPServer)
	w("Config.Settings.SNTP.TimeZone", "+1")
	w("Config.Settings.SNTP.Name", "Netherlands-Amsterdam")
	if in.Ext != nil {
		transport := map[string]int{"udp": 0, "tcp": 1, "tls": 2}[in.Ext.Transport]
		w("Config.Account1.GENERAL.Enable", 1)
		w("Config.Account1.GENERAL.Label", clean(in.Ext.Number))
		w("Config.Account1.GENERAL.DisplayName", clean(in.Ext.Name))
		w("Config.Account1.GENERAL.AuthName", in.Ext.Number)
		w("Config.Account1.GENERAL.UserName", in.Ext.Number)
		w("Config.Account1.GENERAL.Pwd", clean(in.Ext.SIPSecret))
		w("Config.Account1.SIP.Server", in.Server)
		w("Config.Account1.SIP.Port", in.port())
		w("Config.Account1.SIP.TransType", transport)
		w("Config.Account1.SIP.Expire", 300)
		w("Config.Account1.DTMF.Type", 1) // RFC 2833
		if in.Ext.SRTP {
			w("Config.Account1.ENCRYPTION.Enable", 1)
		}
		// Intercom: a door or loading bay station answers every call on its speaker.
		w("Config.Account1.AUTO_ANSWER.Enable", b2i(in.Phone.Options.Intercom.Allow))
	} else {
		w("Config.Account1.GENERAL.Enable", 0)
	}
	return b.String()
}

// Cisco builds the per-phone flat profile of a Cisco 6800/7800/8800 phone with multiplatform
// (MPP / 3PCC) firmware.
func Cisco(in Input) string {
	var b strings.Builder
	w := func(tag string, v any) { fmt.Fprintf(&b, "  <%s ua=\"na\">%s</%s>\n", tag, x(fmt.Sprint(v)), tag) }
	b.WriteString("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by Kiestoon -->\n<flat-profile>\n")
	w("Admin_Password", in.Settings.AdminPassword)
	w("Primary_NTP_Server", in.Settings.NTPServer)
	w("Time_Zone", "GMT+01:00")
	w("Daylight_Saving_Time_Enable", "Yes")
	w("Daylight_Saving_Time_Rule", "start=3/-1/7/2;end=10/-1/7/3;save=1")
	w("Time_Format", "24hr")
	w("Date_Format", "day/month")
	if in.Settings.Lang() == "nl" {
		w("Language_Selection", "Dutch")
	} else {
		w("Language_Selection", "English-US")
	}
	w("Voice_Mail_Number", "*97")
	if in.Ext != nil {
		w("Line_Enable_1_", "Yes")
		w("Extension_1_", 1)
		w("Short_Name_1_", clean(in.Ext.Number))
		w("Display_Name_1_", clean(in.Ext.Name))
		w("User_ID_1_", in.Ext.Number)
		w("Password_1_", clean(in.Ext.SIPSecret))
		w("Auth_ID_1_", in.Ext.Number)
		w("Use_Auth_ID_1_", "Yes")
		w("Proxy_1_", fmt.Sprintf("%s:%d", in.Server, in.port()))
		w("Register_1_", "Yes")
		w("Register_Expires_1_", 300)
		w("Make_Call_Without_Reg_1_", "No")
		w("SIP_Transport_1_", strings.ToUpper(in.Ext.Transport))
		w("DTMF_Tx_Method_1_", "AVT")
		w("Preferred_Codec_1_", "G722")
		w("Message_Waiting_1_", "Yes")
		if in.Ext.SRTP {
			w("Secure_Call_Option_1_", "Required")
		}
	} else {
		w("Line_Enable_1_", "No")
	}
	// Keys 2 and up: BLF with pickup, or speed dial, on the first line.
	for i, k := range simpleKeys(in.Phone.Keys) {
		n := i + 2
		switch k.Type {
		case "blf":
			w(fmt.Sprintf("Extension_%d_", n), "Disabled")
			w(fmt.Sprintf("Short_Name_%d_", n), clean(k.Label))
			w(fmt.Sprintf("Extended_Function_%d_", n), fmt.Sprintf("fnc=blf+sd+cp;sub=%s@%s;nme=%s", k.Value, in.Server, clean(k.Label)))
		case "speed":
			w(fmt.Sprintf("Extension_%d_", n), "Disabled")
			w(fmt.Sprintf("Short_Name_%d_", n), clean(k.Label))
			w(fmt.Sprintf("Extended_Function_%d_", n), fmt.Sprintf("fnc=sd;ext=%s@%s;nme=%s", k.Value, in.Server, clean(k.Label)))
		}
	}
	// Intercom: answer pages and intercom calls (Call-Info answer-after) on the speaker.
	w("Auto_Answer_Page", yesNo(in.Phone.Options.Intercom.Allow))
	if in.PhonebookURL != "" {
		w("XML_Directory_Service_Name", clean(in.Org))
		w("XML_Directory_Service_URL", in.PhonebookURL)
	}
	if in.Firmware != "" {
		w("Upgrade_Enable", "Yes")
		w("Upgrade_Rule", in.Firmware)
	}
	b.WriteString("</flat-profile>\n")
	return b.String()
}

func yesNo(v bool) string {
	if v {
		return "Yes"
	}
	return "No"
}

// CiscoCommon answers the first request of a factory-new Cisco MPP phone (<model>.xml, from DHCP
// option 66 or 150): it moves the phone to its own file, with the credentials in the profile rule.
func CiscoCommon(base string) string {
	rule := base + "cisco/$MA.xml"
	if u, err := url.Parse(base); err == nil && u.User != nil {
		pw, _ := u.User.Password()
		user := u.User.Username()
		u.User = nil
		rule = fmt.Sprintf("[--uid %s --pwd %s]%scisco/$MA.xml", user, pw, u.String())
	}
	return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by Kiestoon -->\n<flat-profile>\n" +
		"  <Provision_Enable ua=\"na\">Yes</Provision_Enable>\n  <Resync_On_Reset ua=\"na\">Yes</Resync_On_Reset>\n" +
		"  <Resync_Periodic ua=\"na\">3600</Resync_Periodic>\n  <Profile_Rule ua=\"na\">" + x(rule) + "</Profile_Rule>\n</flat-profile>\n"
}

// SnomFirmware is the file the firmware_status setting of a Snom points to.
func SnomFirmware(url string) string {
	return "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<firmware-settings>\n  <firmware perm=\"R\">" + x(url) + "</firmware>\n</firmware-settings>\n"
}
